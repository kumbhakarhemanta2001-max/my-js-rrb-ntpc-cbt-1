function runTimer() {

    clearInterval(qTimer);

    qTimer = setInterval(function () {

        let minutes = Math.floor(secLeft / 60);
        let seconds = secLeft % 60;

        seconds = seconds < 10 ? "0" + seconds : seconds;

        document.getElementById("timer-box").innerHTML =
            minutes + ":" + seconds;

        secLeft--;

        // সময় শেষ হলে কুইজ শেষ
        if (secLeft < 0) {

            clearInterval(qTimer);

            showFinalSummary();
        }

    }, 1000);
}

function displayNextQuestion() {

    if (curQ >= qData.length) {

        showFinalSummary();

        return;
    }

    // নেক্সট বাটন হাইড
    document.getElementById("next-btn-container").style.display = "none";

    var currentData = qData[curQ];

    document.getElementById("quiz-progress").innerHTML =
        "প্রশ্ন: " + (curQ + 1) + " / " + qData.length;

    document.getElementById("main-q-text").innerHTML =
        (curQ + 1) + ". " + currentData.q;

    // Image support
    if (currentData.img) {

        document.getElementById("main-q-text").innerHTML +=
            `<br><br>
            <img src="${currentData.img}"
            style="max-width:100%;width:320px;border-radius:10px;">`;
    }

    var optContainer =
        document.getElementById("main-opt-container");

    optContainer.innerHTML = "";

    currentData.opts.forEach(function (val) {

        var b = document.createElement("button");

        b.className = "opt-btn";

        b.innerHTML = val;

        b.onclick = function () {

            validateUserChoice(b, val);
        };

        optContainer.appendChild(b);
    });
}

